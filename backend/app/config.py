"""Runtime configuration, read from environment variables.

Nothing here is secret except the optional LLM API key, which is only read
from the environment and never logged or returned by the API.
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = Path(os.getenv("FD_DATA_DIR", BACKEND_DIR / "data"))
VAR_DIR = Path(os.getenv("FD_VAR_DIR", BACKEND_DIR / "var"))
EVENTS_PATH = DATA_DIR / "events.parquet"
AUDIT_DB_PATH = VAR_DIR / "audit.sqlite3"

# Dataset calendar (fixed so the dataset is reproducible).
DATA_START = date(2026, 5, 25)
DATA_END = date(2026, 8, 16)  # inclusive

# Default comparison windows used across the product (4 weeks vs 4 weeks).
DEFAULT_BASELINE = (date(2026, 6, 22), date(2026, 7, 19))
DEFAULT_CURRENT = (date(2026, 7, 20), date(2026, 8, 16))

DISCLAIMER = (
    "All data in Funnel Detective is synthetic and generated by a reproducible script. "
    "This is an independent portfolio project and is not an official Property Finder product; "
    "no figures represent real Property Finder users, listings, or performance."
)


@dataclass(frozen=True)
class Settings:
    llm_provider: str = field(default_factory=lambda: os.getenv("FD_LLM_PROVIDER", "auto").lower())
    anthropic_api_key: str | None = field(default_factory=lambda: os.getenv("ANTHROPIC_API_KEY") or None)
    llm_model: str = field(default_factory=lambda: os.getenv("FD_LLM_MODEL", "claude-opus-5-5"))
    llm_timeout_s: float = field(default_factory=lambda: float(os.getenv("FD_LLM_TIMEOUT_S", "60")))
    sql_row_limit: int = field(default_factory=lambda: int(os.getenv("FD_SQL_ROW_LIMIT", "500")))
    sql_timeout_s: float = field(default_factory=lambda: float(os.getenv("FD_SQL_TIMEOUT_S", "5")))
    cors_origins: tuple[str, ...] = field(
        default_factory=lambda: tuple(
            o.strip()
            for o in os.getenv("FD_CORS_ORIGINS", "http://localhost:3000,http://127.0.0.1:3000").split(",")
            if o.strip()
        )
    )

    @property
    def llm_enabled(self) -> bool:
        if self.llm_provider in ("none", "deterministic", "off"):
            return False
        return self.anthropic_api_key is not None


def get_settings() -> Settings:
    return Settings()
